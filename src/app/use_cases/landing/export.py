"""
Landing Page → Shopify Liquid & WordPress exporters.
Reuses all text-cleaning / extraction from landing_html_render v7.
Produces platform-ready output that can be pasted directly into each CMS.
"""
from __future__ import annotations
import re
from domain.repositories.landing_page_repository import LandingPageRepository
from domain.repositories.brand_repository import BrandRepository

from app.use_cases.landing.html_render import (
    LandingRenderError, Theme,
    _extract_title, _clean_body, _extract_field,
    _extract_benefits, _extract_testimonials, _extract_faqs,
    _extract_offer, _extract_cta_text, _e, _strip_markdown,
    _rgba, _lighten,
)


class LandingExporter:
    """Multi-format landing page exporter."""

    def __init__(self, lp_repo: LandingPageRepository, brand_repo: BrandRepository):
        self._lp = lp_repo
        self._br = brand_repo

    async def _load(self, lp_id: str):
        lp = await self._lp.get_by_id(lp_id)
        if not lp:
            raise LandingRenderError("not found")
        brand = await self._br.get_by_id(lp.brand_id) if lp.brand_id else None
        c = brand.color_palette or {} if brand else {}
        ty = brand.typography or {} if brand else {}
        theme = Theme(
            primary=c.get("primary", "#6D28D9"),
            secondary=c.get("secondary", "#1E1B4B"),
            accent=c.get("accent", "#A78BFA"),
            background=c.get("background", "#ffffff"),
            text=c.get("text", "#111827"),
            heading_font=ty.get("heading_font", "Outfit"),
            body_font=ty.get("body_font", "DM Sans"),
        )
        brand_name = brand.name if brand else lp.name
        sections = sorted([s for s in lp.sections if s.is_visible], key=lambda x: x.order)
        return lp, brand_name, theme, sections

    async def export_shopify(self, lp_id: str) -> str:
        lp, brand_name, theme, sections = await self._load(lp_id)
        parts = [_shopify_header(lp.name, brand_name, theme)]
        for sec in sections:
            parts.append(_shopify_section(sec, theme))
        parts.append(_shopify_footer(brand_name))
        return "\n".join(parts)

    async def export_wordpress(self, lp_id: str) -> str:
        lp, brand_name, theme, sections = await self._load(lp_id)
        parts = [_wp_header(lp.name, theme)]
        for sec in sections:
            parts.append(_wp_section(sec, theme))
        parts.append(_wp_footer(brand_name))
        return "\n".join(parts)


