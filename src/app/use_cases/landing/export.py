def _shopify_section(section, t: Theme) -> str:
    st = section.section_type
    title = _extract_title(section)
    raw = section.body or ""
    ct = section.content or {}

    if st == "hero":
        sub = ct.get("subtitle") or _extract_field(raw, "subtítulo", "subtitular", "subheadline") or ""
        if not sub:
            lines = _clean_body(raw, exclude_title=title)
            sub = lines[0] if lines else ""
        trust = ct.get("trust_line") or _extract_field(raw, "confianza", "trust line") or ""
        cta = _extract_cta_text(raw)
        return f"""<section class="lp-hero lp-section">
  <div class="lp-container">
    <h1>{_e(title)}</h1>
    <p class="subtitle">{_e(sub)}</p>
    <a href="{{{{ section.settings.cta_url | default: '#' }}}}" class="lp-btn lp-btn-primary">{_e(cta)}</a>
    {f'<p class="trust">{_e(trust)}</p>' if trust else ''}
  </div>
</section>"""

    if st == "social_proof":
        stats = ct.get("stats", [])
        if not stats:
            for m in re.finditer(r"\+?([\d.,]+[kKmM+]*)\s+((?:clientes?|equipos?|usuarios?)[^\n.]*)", raw, re.IGNORECASE):
                stats.append({"value": f"+{m.group(1)}", "label": _strip_markdown(m.group(2).strip())})
        items = "".join(f'<div><div class="value">{_e(str(s.get("value","")))}</div><div class="label">{_e(s.get("label",""))}</div></div>' for s in stats[:4])
        return f'<section class="lp-section"><div class="lp-container"><div class="lp-proof">{items}</div></div></section>'

    if st in ("problem", "solution"):
        labels = {"problem": "El problema", "solution": "La solución"}
        lines = _clean_body(raw, exclude_title=title)
        body = "\n".join(f"    <p>{_e(l)}</p>" for l in lines if len(l) > 10)
        return f"""<section class="lp-section">
  <div class="lp-container">
    <div class="lp-text-block">
      <p class="lp-label">{labels.get(st, "")}</p>
      <h2 class="lp-title">{_e(title) or labels.get(st, "")}</h2>
{body}
    </div>
  </div>
</section>"""

    if st in ("features", "benefits"):
        items = ct.get("items") or _extract_benefits(raw)
        label = "Beneficios" if st == "benefits" else "Características"
        cards = "".join(f"""    <div class="lp-benefit">
      <div class="icon">{i.get("icon","✦")}</div>
      <h3>{_e(i.get("title",""))}</h3>
      <p>{_e(i.get("description",""))}</p>
    </div>\n""" for i in items)
        return f"""<section class="lp-section">
  <div class="lp-container">
    <p class="lp-label" style="text-align:center">{label}</p>
    <h2 class="lp-title" style="text-align:center">{_e(title) or label}</h2>
    <div class="lp-benefits">
{cards}    </div>
  </div>
</section>"""

    if st == "transformation":
        before = _extract_field(raw, "antes", "izquierda") or "Frustración y batería muerta."
        after = _extract_field(raw, "después", "derecha") or "Velocidad, cámara pro, todo el día."
        return f"""<section class="lp-section">
  <div class="lp-container">
    <p class="lp-label" style="text-align:center">Transformación</p>
    <h2 class="lp-title" style="text-align:center">{_e(title)}</h2>
    <div class="lp-transform">
      <div class="before"><h4>😤 Antes</h4><p>{_e(before)}</p></div>
      <div class="after"><h4>🤩 Después</h4><p>{_e(after)}</p></div>
    </div>
  </div>
</section>"""

    if st in ("offer", "pricing"):
        offer = _extract_offer(raw)
        old_p = ct.get("price_old") or offer.get("price_old", "")
        new_p = ct.get("price_new") or offer.get("price_new", "")
        guarantee = ct.get("guarantee") or offer.get("guarantee", "")
        checks = offer.get("checklist", [])
        cta = _extract_cta_text(raw)
        checks_html = "<ul>" + "".join(f"<li>{_e(c)}</li>" for c in checks) + "</ul>" if checks else ""
        return f"""<section class="lp-section">
  <div class="lp-container">
    <p class="lp-label" style="text-align:center">Oferta especial</p>
    <h2 class="lp-title" style="text-align:center">{_e(title) or 'Tu oferta'}</h2>
    <div class="lp-offer">
      {f'<div class="old">{_e(old_p)}</div>' if old_p else ''}
      {f'<div class="new">{_e(new_p)}</div>' if new_p else ''}
      {checks_html}
      {f'<div class="guarantee">🛡️ {_e(guarantee)}</div>' if guarantee else ''}
      <a href="{{{{ section.settings.cta_url | default: '/cart' }}}}" class="lp-btn lp-btn-primary" style="margin-top:28px">{_e(cta)}</a>
    </div>
  </div>
</section>"""

    if st == "testimonials":
        items = ct.get("testimonials") or _extract_testimonials(raw)
        cards = "".join(f"""    <div class="lp-testimonial">
      <div class="stars">{"★" * int(i.get("rating", 5))}</div>
      <p class="quote">"{_e(i.get("text",""))}"</p>
      <p class="author">{_e(i.get("name",""))}</p>
    </div>\n""" for i in items)
        return f"""<section class="lp-section">
  <div class="lp-container">
    <p class="lp-label" style="text-align:center">Testimonios</p>
    <h2 class="lp-title" style="text-align:center">{_e(title) or 'Nuestros clientes'}</h2>
    <div class="lp-testimonials">
{cards}    </div>
  </div>
</section>"""

    if st == "faq":
        items = ct.get("items") or _extract_faqs(raw)
        faqs = "".join(f'<div class="lp-faq-item"><h3>{_e(i["question"])}</h3><p>{_e(i["answer"])}</p></div>' for i in items)
        return f"""<section class="lp-section">
  <div class="lp-container">
    <p class="lp-label" style="text-align:center">Preguntas frecuentes</p>
    <h2 class="lp-title" style="text-align:center">{_e(title) or 'Preguntas frecuentes'}</h2>
    <div class="lp-faq">{faqs}</div>
  </div>
</section>"""

    if st == "cta":
        lines = _clean_body(raw, exclude_title=title)
        body = "\n".join(f"    <p>{_e(l)}</p>" for l in lines if len(l) > 10)
        cta = _extract_cta_text(raw)
        return f"""<section class="lp-cta lp-section">
  <div class="lp-container">
    <h2>{_e(title) or 'No esperes más'}</h2>
{body}
    <a href="{{{{ section.settings.cta_url | default: '/cart' }}}}" class="lp-btn lp-btn-white">{_e(cta)}</a>
  </div>
</section>"""

    # Fallback
    lines = _clean_body(raw, exclude_title=title)
    body = "\n".join(f"<p>{_e(l)}</p>" for l in lines)
    return f'<section class="lp-section"><div class="lp-container"><div class="lp-text-block"><h2 class="lp-title">{_e(title)}</h2>{body}</div></div></section>'


